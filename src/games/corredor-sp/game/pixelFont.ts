const GLYPHS: Record<string, string[]> = Object.fromEntries(Object.entries(G).map(([k, v]) => [k, v.split('/')]));
const ACCENTS: Record<string, string> = { Á: 'A', Ã: 'A', Â: 'A', À: 'A', É: 'E', Ê: 'E', Í: 'I', Ó: 'O', Õ: 'O', Ô: 'O', Ú: 'U', Ç: 'C' };

export const textWidth = (s: string, scale = 1) => (s.length * 4 - 1) * scale;

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  shadow: string | null = '#1b1220',
) {
  const s = text.toUpperCase();
  const pass = (ox: number, oy: number, col: string) => {
    ctx.fillStyle = col;
    let cx = Math.round(x) + ox;
    for (const raw of s) {
      const g = GLYPHS[ACCENTS[raw] ?? raw] ?? GLYPHS[' '];
      for (let gy = 0; gy < 5; gy++) {
        for (let gx = 0; gx < 3; gx++) {
          if (g[gy][gx] === '#') ctx.fillRect(cx + gx * scale, Math.round(y) + oy + gy * scale, scale, scale);
        }
      }
      cx += 4 * scale;
    }
  };
  if (shadow) pass(scale, scale, shadow);
  pass(0, 0, color);
}
